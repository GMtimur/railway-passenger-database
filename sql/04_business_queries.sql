-- Аналитические запросы для демонстрационных данных проекта.
-- Статус «Активен» означает, что билет не возвращён.
-- Сумма активных билетов не учитывает комиссии и частичные возвраты:
-- эти сведения отсутствуют в модели.

-- 1. Какие маршруты дают наибольшую сумму по активным билетам?
-- Маршруты без продаж также включаются в результат.
SELECT
    м.код_маршрута,
    COUNT(б.номер_билета) AS активных_билетов,
    COALESCE(SUM(б.цена), 0) AS сумма_активных_билетов
FROM маршрут AS м
LEFT JOIN рейс AS р
    ON р.код_маршрута = м.код_маршрута
LEFT JOIN билет AS б
    ON б.номер_рейса = р.номер_рейса
    AND б.дата_отправления_рейса = р.дата_отправления
    AND б.статус_возврата = 'Активен'
GROUP BY м.код_маршрута
ORDER BY сумма_активных_билетов DESC, м.код_маршрута;

-- 2. Сколько билетов оформлено на каждый рейс и какая доля возвращена?
-- Рейс определяется номером и датой отправления.
-- Знаменатель доли возвратов — все оформленные билеты.
-- Для рейса без билетов доля равна NULL, а не 0%.
SELECT
    р.номер_рейса,
    р.дата_отправления,
    COUNT(б.номер_билета) AS оформлено_билетов,
    COUNT(б.номер_билета) FILTER (
        WHERE б.статус_возврата = 'Активен'
    ) AS активных_билетов,
    COUNT(б.номер_билета) FILTER (
        WHERE б.статус_возврата = 'Возвращён'
    ) AS возвращено_билетов,
    ROUND(
        100.0 * COUNT(б.номер_билета) FILTER (
            WHERE б.статус_возврата = 'Возвращён'
        ) / NULLIF(COUNT(б.номер_билета), 0),
        2
    ) AS доля_возвратов_проц
FROM рейс AS р
LEFT JOIN билет AS б
    ON б.номер_рейса = р.номер_рейса
    AND б.дата_отправления_рейса = р.дата_отправления
GROUP BY р.номер_рейса, р.дата_отправления
ORDER BY р.дата_отправления, р.номер_рейса;

-- 3. У каких рейсов фактические дата и время позже плановых?
-- Используем полные даты и время, чтобы учитывать переход через полночь.
-- Записи без планового или фактического времени исключаются из сравнения.
WITH время_рейсов AS (
    SELECT
        номер_рейса,
        дата_отправления,
        код_маршрута,
        плановая_дата + время_отправления AS плановое_время,
        реальная_дата + реальное_время AS фактическое_время,
        причина_задержки
    FROM рейс
)
SELECT
    номер_рейса,
    дата_отправления,
    код_маршрута,
    плановое_время,
    фактическое_время,
    ROUND(
        EXTRACT(EPOCH FROM (
            фактическое_время - плановое_время
        )) / 60,
        2
    ) AS задержка_минут,
    причина_задержки
FROM время_рейсов
WHERE фактическое_время > плановое_время
ORDER BY задержка_минут DESC, номер_рейса, дата_отправления;

-- 4. Какие пассажиры имеют наибольшую сумму активных билетов?
-- Рейтинг включает только пассажиров с активными билетами.
-- Равные суммы получают одинаковое место без пропусков в рейтинге.
WITH суммы_пассажиров AS (
    SELECT
        паспорт_пассажира,
        COUNT(*) AS активных_билетов,
        SUM(цена) AS сумма_активных_билетов
    FROM билет
    WHERE статус_возврата = 'Активен'
    GROUP BY паспорт_пассажира
)
SELECT
    DENSE_RANK() OVER (
        ORDER BY с.сумма_активных_билетов DESC
    ) AS место_в_рейтинге,
    п.фио,
    с.активных_билетов,
    с.сумма_активных_билетов
FROM суммы_пассажиров AS с
JOIN пассажир AS п
    ON п.серия_и_номер_паспорта = с.паспорт_пассажира
ORDER BY место_в_рейтинге, п.фио, с.паспорт_пассажира;

-- 5. Каковы средняя стоимость и диапазон цен активных билетов по маршрутам?
-- Количество билетов показывает размер выборки для средней цены.
-- Для маршрутов без активных билетов ценовые показатели равны NULL.
SELECT
    м.код_маршрута,
    COUNT(б.номер_билета) AS активных_билетов,
    ROUND(AVG(б.цена), 2) AS средняя_цена,
    MIN(б.цена) AS минимальная_цена,
    MAX(б.цена) AS максимальная_цена
FROM маршрут AS м
LEFT JOIN рейс AS р
    ON р.код_маршрута = м.код_маршрута
LEFT JOIN билет AS б
    ON б.номер_рейса = р.номер_рейса
    AND б.дата_отправления_рейса = р.дата_отправления
    AND б.статус_возврата = 'Активен'
GROUP BY м.код_маршрута
ORDER BY средняя_цена DESC NULLS LAST, м.код_маршрута;

-- 6. Какие типы вагонов назначены в составы и есть ли неготовые вагоны?
-- Назначение — строка таблицы вагон_в_составе.
-- Один физический вагон может иметь несколько назначений.
-- Статус ТО берётся из текущей записи вагона, история ТО не хранится.
-- Запрос выявляет назначения неготовых вагонов, но не запрещает их.
SELECT
    в.тип_вагона,
    COUNT(*) AS назначений_в_составы,
    COUNT(DISTINCT в.номер_вагона) AS уникальных_вагонов,
    SUM(
        CASE
            WHEN в.статус_то <> 'Готов' THEN 1
            ELSE 0
        END
    ) AS назначений_неготовых_вагонов
FROM вагон_в_составе AS вс
JOIN вагон AS в
    ON в.номер_вагона = вс.номер_вагона
GROUP BY в.тип_вагона
ORDER BY назначений_в_составы DESC, в.тип_вагона;

-- 7. Сколько билетов куплено в каждый день и какие остаются активными?
-- Группировка по дате покупки, статусы отражают текущее состояние.
-- Дата возврата отсутствует: этот запрос не показывает возвраты по дням
-- и не восстанавливает историческое состояние продаж.
SELECT
    дата_покупки,
    COUNT(*) AS оформлено_билетов,
    COUNT(*) FILTER (
        WHERE статус_возврата = 'Активен'
    ) AS активных_сейчас,
    COUNT(*) FILTER (
        WHERE статус_возврата = 'Возвращён'
    ) AS возвращённых_сейчас,
    SUM(
        CASE
            WHEN статус_возврата = 'Активен' THEN цена
            ELSE 0
        END
    ) AS сумма_активных_билетов
FROM билет
GROUP BY дата_покупки
ORDER BY дата_покупки;
