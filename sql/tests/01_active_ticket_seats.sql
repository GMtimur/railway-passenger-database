-- Выполнять после загрузки исходных тестовых данных.
-- На рейс 100 от 2026-06-01 есть возвращённый билет:
-- вагон 2, место 25. Повторная продажа должна быть разрешена.
-- Все изменения этой проверки отменяются командой ROLLBACK.
BEGIN;

DO $$
DECLARE
    constraint_name TEXT;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM билет
        WHERE номер_билета = '20260601100003'
          AND статус_возврата = 'Возвращён'
          AND номер_рейса = '100'
          AND дата_отправления_рейса = DATE '2026-06-01'
          AND номер_вагона = 2
          AND номер_места = 25
    ) THEN
        RAISE EXCEPTION 'Не найден исходный возвращённый билет для проверки';
    END IF;

    INSERT INTO билет (
        номер_билета, паспорт_пассажира, номер_рейса,
        дата_отправления_рейса, номер_вагона, номер_места,
        цена, дата_покупки, статус_возврата
    ) VALUES (
        'test_resale_01', '4515-123456', '100',
        '2026-06-01', 2, 25, 2800.00, '2026-05-28', 'Активен'
    );
    RAISE NOTICE 'OK: место возвращённого билета продано повторно';

    BEGIN
        INSERT INTO билет (
            номер_билета, паспорт_пассажира, номер_рейса,
            дата_отправления_рейса, номер_вагона, номер_места,
            цена, дата_покупки, статус_возврата
        ) VALUES (
            'test_duplicate_02', '4516-234567', '100',
            '2026-06-01', 2, 25, 2800.00, '2026-05-28', 'Активен'
        );
        RAISE EXCEPTION 'Проверка не пройдена: два активных билета на одно место разрешены';
    EXCEPTION WHEN unique_violation THEN
        GET STACKED DIAGNOSTICS constraint_name = CONSTRAINT_NAME;
        IF constraint_name IS DISTINCT FROM 'unique_active_place' THEN
            RAISE;
        END IF;
        RAISE NOTICE 'OK: второй активный билет на то же место отклонён';
    END;
END;
$$;

ROLLBACK;
