-- Обновление базы, созданной с исходным ограничением unique_place.
-- При новом запуске проекта изменение уже включено в 01_schema.sql:
-- в этом случае выполнять этот файл не нужно.
-- Транзакция сохраняет прежнее ограничение, если обновление не выполнится.
BEGIN;

ALTER TABLE билет DROP CONSTRAINT unique_place;

CREATE UNIQUE INDEX unique_active_place
    ON билет (номер_рейса, дата_отправления_рейса, номер_вагона, номер_места)
    WHERE статус_возврата = 'Активен';

COMMIT;
